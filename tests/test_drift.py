"""Holds nomadpy to the exported surface of the pinned Go api module.

oracle/fixtures/surface.json is generated by `make oracle`; oracle/ledger.json
lists every deliberate gap. Anything else that differs is drift and fails.

Rules that need no ledger entry:
- a Go file maps to the Python module of the same stem;
- `Client.<Service>()` constructors map to `self.<service> = <Service>(self)` in Client.__init__;
- Len/Less/Swap on *Sort receivers, and methods on unexported receivers, are Go-only;
- methods on structs the ledger lists as dicts are Go-only;
- a Go `Foo`/`FooOpts` pair maps to one Python method `foo`;
- structs named *Request and *Options are request bodies or keyword arguments, not models;
- a Go struct whose Python class is not a Model (services, Client, options, the exception) is not field-compared;
- embedded fields (QueryMeta, WriteMeta, WriteRequest) are not model fields;
- Go consts map to UPPER_SNAKE names in the same module.
"""

import dataclasses
import importlib
import inspect
import json
import re
from pathlib import Path

import pytest

import nomadpy
from nomadpy.models import Model, json_name

ROOT = Path(__file__).resolve().parent.parent
SURFACE = json.loads((ROOT / "oracle/fixtures/surface.json").read_text())
LEDGER = json.loads((ROOT / "oracle/ledger.json").read_text())
PACKAGE = Path(nomadpy.__file__).parent
CLIENT_INIT = inspect.getsource(nomadpy.Client.__init__)


def is_model(cls) -> bool:
    return isinstance(cls, type) and issubclass(cls, Model) and cls is not Model


def snake(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()


def module_for(go_file: str):
    stem = go_file.removesuffix(".go")
    if not (PACKAGE / f"{stem}.py").exists():
        return None
    return importlib.import_module(f"nomadpy.{stem}")


def ported_files():
    return [f for f in SURFACE["files"] if module_for(f) is not None]


def test_pinned_version_is_recorded():
    assert SURFACE["module"] == "github.com/hashicorp/nomad/api"
    assert SURFACE["version"].startswith("v")


@pytest.mark.parametrize("go_file", sorted(SURFACE["files"]))
def test_file_is_ported_or_in_ledger(go_file):
    module = module_for(go_file)
    listed = go_file in LEDGER["files"]
    if module is None:
        assert listed, f"{go_file} has no Python module and no ledger entry"
    else:
        assert not listed, f"{go_file} is ported; remove its ledger entry"


def test_ledger_files_exist_upstream():
    assert set(LEDGER["files"]) <= set(SURFACE["files"])


@pytest.mark.parametrize("go_file", ported_files())
def test_methods(go_file):
    module = module_for(go_file)
    go_methods = SURFACE["files"][go_file]["methods"]
    problems = []
    expected_python = {}  # (class, python method) -> Go method
    for m in go_methods:
        receiver, name = m["receiver"], m["name"]
        key = f"{receiver}.{name}"
        if receiver[0].islower():
            continue
        if receiver.endswith("Sort") and name in ("Len", "Less", "Swap"):
            continue
        if receiver == "Client" and name == struct_service_name(go_file, name):
            if f"self.{snake(name)} = {name}(self)" not in CLIENT_INIT:
                problems.append(f"Client.{name}() has no `self.{snake(name)} = {name}(self)` in Client.__init__")
            continue
        if receiver in LEDGER["structs"].get(go_file, {}) and receiver != "Client":
            continue
        if receiver in LEDGER["receivers"]:
            continue
        entry = LEDGER["methods"].get(key)
        if isinstance(entry, str):
            continue
        cls = getattr(nomadpy.api if receiver == "Client" else module, receiver, None)
        if cls is None:
            problems.append(f"{key}: receiver has no Python class and no ledger entry")
            continue
        if isinstance(entry, dict):
            python_name = entry["folded"]
        elif name.endswith("Opts") and any(x["receiver"] == receiver and x["name"] == name[:-4] for x in go_methods):
            python_name = snake(name[:-4])
        else:
            python_name = snake(name)
        if not callable(getattr(cls, python_name, None)):
            problems.append(f"{key}: expected {receiver}.{python_name} in nomadpy.{module.__name__.rsplit('.', 1)[-1]}")
        expected_python[(receiver, python_name)] = key

    for receiver in {m["receiver"] for m in go_methods}:
        cls = getattr(nomadpy.api if receiver == "Client" else module, receiver, None)
        if cls is None or receiver in LEDGER["structs"].get(go_file, {}):
            continue
        if receiver in LEDGER["receivers"] or receiver == "Client":
            continue
        for python_name, member in inspect.getmembers(cls, callable):
            if python_name.startswith("_") or hasattr(Model, python_name):
                continue
            if (receiver, python_name) not in expected_python:
                problems.append(f"{receiver}.{python_name} exists in Python but has no Go counterpart in {go_file}")
    assert not problems, "\n".join(problems)


def struct_service_name(go_file: str, name: str) -> str | None:
    """Returns name when it is the service struct of go_file (Jobs for jobs.go), else None."""
    return name if name in SURFACE["files"][go_file]["structs"] and name == name_of_service(go_file) else None


def name_of_service(go_file: str) -> str | None:
    for m in SURFACE["files"][go_file]["methods"]:
        if m["receiver"] == "Client" and m["name"] in SURFACE["files"][go_file]["structs"]:
            return m["name"]
    return None


@pytest.mark.parametrize("go_file", ported_files())
def test_structs(go_file):
    module = module_for(go_file)
    go_structs = SURFACE["files"][go_file]["structs"]
    ledger = LEDGER["structs"].get(go_file, {})
    problems = []
    for name, st in go_structs.items():
        if name.endswith(("Request", "Options")):
            continue
        cls = getattr(module, name, None)
        if name in ledger:
            if is_model(cls):
                problems.append(f"{name} is a Model now; remove its ledger entry")
            continue
        if cls is None:
            problems.append(f"{name}: no Python class and no ledger entry")
            continue
        if not is_model(cls):
            continue
        go_fields = {f["json"] for f in st["fields"] if not f.get("embedded")}
        py_fields = {f.metadata.get("json", json_name(f.name)) for f in dataclasses.fields(cls)}
        for missing in sorted(go_fields - py_fields):
            problems.append(f"{name}: Go field {missing} is not on the dataclass")
        for extra in sorted(py_fields - go_fields):
            problems.append(f"{name}: dataclass field {extra} does not exist in Go")

    for name, cls in inspect.getmembers(module, is_model):
        if cls.__module__ == module.__name__ and name not in go_structs:
            problems.append(f"{name}: Model has no Go struct in {go_file}")
    for name in ledger:
        if name not in go_structs:
            problems.append(f"ledger lists {name}, which {go_file} no longer defines")
    assert not problems, "\n".join(problems)


@pytest.mark.parametrize("go_file", ported_files())
def test_consts(go_file):
    module = module_for(go_file)
    ledger = LEDGER["consts"].get(go_file, {})
    problems = []
    for c in SURFACE["files"][go_file]["consts"]:
        name = c["name"]
        python_name = snake(name).upper()
        if name in ledger:
            if hasattr(module, python_name):
                problems.append(f"{name} is defined now; remove its ledger entry")
            continue
        if not hasattr(module, python_name):
            problems.append(f"{name}: expected {python_name} = {c['value']}")
        elif c["value"].startswith('"') and getattr(module, python_name) != json.loads(c["value"]):
            problems.append(f"{python_name} is {getattr(module, python_name)!r}, Go has {c['value']}")
    assert not problems, "\n".join(problems)
